# Індивідуальне завдання (Варіант 10): Заміна пробілів на символ підкреслення
import re

def replace_spaces(text):
    """
    Функція використовує регулярний вираз для пошуку 
    всіх пробілів (\\s) та замінює їх на символ підкреслення (_).
    """
    # \s - це будь-який пробільний символ (звичайний пробіл, табуляція, тощо)
    result = re.sub(r'\s', '_', text)
    return result

def main():
    # Початковий рядок для тестування
    sample_text = "Це тестовий рядок з кількома пробілами та табуляцією."
    
    print("Оригінальний текст:")
    print(sample_text)
    
    # Виклик функції заміни
    modified_text = replace_spaces(sample_text)
    
    print("\nТекст після заміни (результат):")
    print(modified_text)

if __name__ == "__main__":
    main()

# Індивідуальне завдання (Варіант 10): Видалення повторюваних елементів зі списку

# Початковий список із повторюваними елементами
my_list = [10, 10, 20, 30, 10, 40, 50]
print(f"Початковий список: {my_list}")

# Створення нового списку для зберігання унікальних значень
unique_list = []

# Перебір елементів та додавання лише унікальних
for item in my_list:
    if item not in unique_list:
        unique_list.append(item)

# Виведення результату
print(f"Список без повторень: {unique_list}")


# Індивідуальне завдання (Варіант 10): Перезаписати файл лише якщо він існує
import os

filename = "my_data.txt"
new_content = "Цей текст успішно перезаписано, оскільки файл існував!\n"

# Перевіряємо, чи файл вже існує в директорії
if os.path.exists(filename):
    # Відкриваємо в режимі 'w', який зітре старі дані і запише нові
    with open(filename, 'w', encoding='utf-8') as f:
        f.write(new_content)
    print(f"Файл '{filename}' успішно перезаписано новими даними.")
else:
    # Якщо файлу немає, ми нічого не робимо, щоб уникнути його автоматичного створення
    print(f"Помилка: Файл '{filename}' не існує. Перезапис скасовано.")
